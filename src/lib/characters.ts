/**
 * コーチのキャラクター。
 *
 * 変えるのは「言い方」だけで、指導の中身と安全ルールは変えない。
 * 優しいキャラを選んだからといって痛みを見逃す、熱血キャラだから無理をさせる、
 * というのはコーチとして成立しない。
 *
 * id は変えないこと。すでに選んでいる人の設定が、無言で既定値に戻ってしまう。
 */

/** 表示のためだけに持つ。指導内容には一切影響しない。 */
export type CoachGender = 'male' | 'female';

export interface CoachCharacter {
  id: string;
  /** 姓名。 */
  name: string;
  /** ふりがな。 */
  reading: string;
  /** 肩書き。 */
  title: string;
  /** 一言での性格。選ぶ時の手がかり。 */
  tagline: string;
  gender: CoachGender;
  age: string;
  /** 顔写真（public/coaches/）。読めない時は頭文字に落とす。 */
  photo: string;
  /** 写真が出せない端末・通信状況での代替表示。 */
  initial: string;
  /** アイコンの縁と強調に使う色。 */
  color: string;
  /** どんなコーチかを一段落で。 */
  description: string;
  /** 経歴。プロフィール画面に出す。 */
  career: string[];
  /** 得意なこと。 */
  strengths: string[];
  /** こういう人におすすめ。抽象語ではなく、思い当たる場面で書く。 */
  recommendedFor: string[];
  /** 実際にこの人が言いそうな一言。話し方の見本として画面に出す。 */
  sample: string;
  /** プロンプトに差し込む口調の指示。 */
  voice: string[];
}

