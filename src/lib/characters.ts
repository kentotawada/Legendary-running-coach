/**
 * コーチのキャラクター。
 *
 * 変えるのは「言い方」だけで、指導の中身と安全ルールは変えない。
 * 優しいキャラを選んだからといって痛みを見逃す、熱血キャラだから無理をさせる、
 * というのはコーチとして成立しない。
 *
 * id は変えないこと。すでに選んでいる人の設定が、無言で既定値に戻ってしまう。
 */

/** 表示のためだけに持つ。指導内容には一切影響しない。 */
export type CoachGender = 'male' | 'female';

/**
 * そのコーチが、どのくらい走る人を想定しているか。
 *
 * **これは「求められる量」の目安で、コーチの優劣ではない。**
 * 入口に8人の顔だけを並べると、いちばん上に出た人の一言で
 * 「自分向けではなさそうだ」と決まってしまう。走り始めたい人が
 * 「まず数字を見ます」と言う人の隣で迷わないよう、難易度を先に見せる。
 *
 * **指導の中身には一切影響しない。** プロンプトにも渡さない。
 * ここを渡すと「かんたん」のコーチが本気の相談を断りはじめる。
 * 走る量を決めるのは、選んだラベルではなく、その人の記録と段階（phase）。
 */
export type CoachLevel = 'easy' | 'normal' | 'hard' | 'oni';

export interface CoachCharacter {
  id: string;
  /** 姓名。 */
  name: string;
  /** ふりがな。 */
  reading: string;
  /** 肩書き。 */
  title: string;
  /**
   * 顔の下に出る一言。
   *
   * **説明文ではなく、その人が言いそうな言葉にする。**
   * 「数字で説明する」は肩書きの紹介であって、人の言葉ではない。
   * ここが紹介文のままだと、8人並べても求人票が並んでいるようにしか見えない。
   * 一人称で、口に出して言う形で書く。20字前後（2行に収まる長さ）。
   */
  tagline: string;
  /** 想定している走る人の段階。**表示だけに使う。** */
  level: CoachLevel;
  gender: CoachGender;
  age: string;
  /**
   * 顔写真（public/coaches/）。
   * **無い時は指定しない。** 在りもしないパスを書くと、読み込みに失敗してから
   * 頭文字に落ちるので、一瞬だけ空の丸が出る。最初から頭文字で描いたほうが速い。
   */
  photo?: string;
  /** 写真が出せない端末・通信状況での代替表示。 */
  initial: string;
  /** アイコンの縁と強調に使う色。 */
  color: string;
  /** どんなコーチかを一段落で。 */
  description: string;
  /** 経歴。プロフィール画面に出す。 */
  career: string[];
  /** 得意なこと。 */
  strengths: string[];
  /** こういう人におすすめ。抽象語ではなく、思い当たる場面で書く。 */
  recommendedFor: string[];
  /** 実際にこの人が言いそうな一言。話し方の見本として画面に出す。 */
  sample: string;
  /**
   * 話し方の型。
   *
   * **ここが揃っていないと、誰を選んでも同じ文章が返ってくる。**
   * 「優しく」「熱く」のような形容詞では、書く側は何も変えられない。
   * 一人称・二人称・語尾まで決めて、はじめて別人になる。
   */
  speech: {
    first: string;
    /**
     * 相手の名前に付ける敬称。呼び捨てで話す人は空文字。
     *
     * **二人称は持たせない。** 「きみ」「あなた」で呼ばれた文章は、
     * 読んだ人にとって誰に向けたものでもない。名前で呼ばれてはじめて自分の話になる。
     * 名前をまだ聞けていない間は、主語を省いて話す（日本語はそれで通る）。
     */
    honorific: string;
    /** よく使う言い回し。 */
    habits: string[];
    /** この人は絶対に言わない言い方。 */
    never: string[];
  };
  /**
   * 場面ごとの一言。
   * **口調は、説明より例で伝わる。** 褒める時・良くない時・痛みがある時の3つ。
   */
  lines: { when: string; say: string }[];
  /**
   * 画面を開いた時に、コーチのほうから言う一言。
   *
   * **ここが無いと、コーチは顔だけ出して黙っていることになる。**
   * 開いた人が自分から文章を打ち始めるまで何も起きないのでは、コーチではない。
   *
   * 文章はモデルに書かせない。開いた瞬間に出したいので、待たせるわけにいかないし、
   * 開くたびに生成していては、毎日使う道具として費用が見合わない。
   * **事実の部分はコードが作り、言い回しをここが持つ。**
   */
  greet: {
    /** ふだんの切り出し。 */
    hello: string;
    /** しばらく間が空いた後。責めない。 */
    back: string;
    /** 痛みがある時。走らせないと言い切る。ここだけは全員が同じ結論になる。 */
    pain: string;
    /** 最後に投げる問い。**相手が一言で返せる形にする。** */
    ask: string;
    /** まだ記録が1つも無い時。最初の一手だけを渡す。 */
    empty: string;
  };
  /** プロンプトに差し込む口調の指示。 */
  voice: string[];
}

