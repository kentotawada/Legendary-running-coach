export function levelInfo(level: CoachLevel): CoachLevelInfo {
  return COACH_LEVELS.find((item) => item.id === level) ?? COACH_LEVELS[0]!;
}

/**
 * 難易度ごとにコーチを分ける。
 *
 * **空の段は返さない。** 誰も居ない難易度の見出しだけが出ていると、
 * 読み込みに失敗したように見える。
 */
export function charactersByLevel(
  characters: CoachCharacter[] = COACH_CHARACTERS,
): { level: CoachLevelInfo; characters: CoachCharacter[] }[] {
  return COACH_LEVELS.map((level) => ({
    level,
    characters: characters.filter((character) => character.level === level.id),
  })).filter((group) => group.characters.length > 0);
}

export function findCharacter(id: string | undefined): CoachCharacter {
  return COACH_CHARACTERS.find((c) => c.id === id) ?? COACH_CHARACTERS.find((c) => c.id === DEFAULT_CHARACTER_ID)!;
}

/** 姓だけ。画面の見出しなど、短く呼ぶ場所で使う。 */
export function familyName(character: CoachCharacter): string {
  return character.name.split(' ')[0] ?? character.name;
}

/**
 * その人を何と呼ぶか。
 *
 * **名前で呼ばれた言葉だけが、自分に向けられたものとして届く。**
 * 「きみ」「あなた」は誰にでも当てはまるので、誰にも当てはまらない。
 *
 * 名前を聞けていなければ null を返す。**そこで二人称に落とさない。**
 * 日本語は主語を省いて話せるので、呼びかけずに話すほうが自然で、
 * 借り物の「あなた」より距離が近い。
 */
export function addressFor(id: string | undefined, displayName: string | undefined): string | null {
  const name = displayName?.trim();
  if (!name) return null;
  return `${name}${findCharacter(id).speech.honorific}`;
}

/**
 * プロンプトに差し込む口調の指示。
 *
 * @param displayName 呼んでほしい名前。**ここに渡さないと、モデルは呼び方を知らない。**
 */
export function characterVoice(id: string | undefined, displayName?: string): string {
  const character = findCharacter(id);
  const address = addressFor(id, displayName);
  return [
    `# あなたは ${character.name}（${character.reading}）、${character.age}の${character.title}です`,
    '',
    `${character.description}`,
    '',
    '## 話し方',
    ...character.voice.map((line) => `- ${line}`),
    '',
    '## 言葉づかい（ここは必ず守る）',
    `- 自分のことは「${character.speech.first}」と呼ぶ。`,
    // 呼び方。**ここが一番よく破られるので、理由まで書いて強く言う。**
    address
      ? [
          `- 相手のことは「${address}」と呼ぶ。**返事のどこかで必ず一度、名前で呼ぶこと。**`,
          '  「きみ」「あなた」「君」は使わない。名前で呼ばれてはじめて、自分に向けられた言葉になる。',
        ].join('\n')
      : [
          '- 相手の名前をまだ聞けていない。**「きみ」「あなた」「君」で呼ばないこと。**',
          '  日本語は主語を省いて話せる。呼びかけずに話せばよい。',
          '  そのうえで、会話が途切れない場面で一度だけ何と呼べばいいかを尋ね、',
          '  聞けたら update_profile の displayName に記録する。二度は尋ねない。',
        ].join('\n'),
    ...character.speech.habits.map((line) => `- ${line}`),
    `- 言わない: ${character.speech.never.join('、')}。`,
    '',
    '## この人なら、こう言う',
    ...character.lines.map((line) => `- ${line.when}: 「${line.say}」`),
    '',
    '**この例文をそのまま使い回さないこと。** 例は温度と距離感の見本であって、',
    '定型文ではない。同じ人が、その場に合わせて言いそうな言葉を、毎回あたらしく選ぶ。',
    '',
    '**キャラクターは話し方だけを変える。** 指導の中身、安全のルール、',
    '痛みへの配慮、責めない原則は、どのキャラクターでも一切変わらない。',
    'キャラクターらしさのために、事実を曲げたり、危険な判断を勧めたりしてはならない。',
  ].join('\n');
}
