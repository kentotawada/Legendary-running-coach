/**
 * システムプロンプトを毎ターン組み立てる。
 * 固定の人格・指導理論 + その人のカルテ + 今この瞬間の安全ディレクティブ、の三層構造。
 */
export function buildSystemInstruction(profile: RunnerProfile, now: Date = new Date()): string {
  const safety = assessSafety(profile, now);
  const phase = resolvePhase(profile, safety.runningForbidden);
  const transition = transitionGuidance(profile);

  const character = findCharacter(profile.characterId);

  const sections = [
    IDENTITY.replace('{{characterName}}', character.name),
    characterVoice(profile.characterId),
    `今日の日付: ${today(now)}`,
    ABSOLUTE_RULES,
    DOCTRINE,
    goalDoctrine(profile),
    raceDoctrine(profile, now),
    zoneDoctrine(profile),
    phaseGuidance(phase),
    transition,
    summarizeProfile(profile, now),
    dailyDoctrine(profile, now),
    safety.directives.length > 0
      ? ['# 安全のための強制指示', ...safety.directives.map((d) => `- ${d}`)].join('\n')
      : null,
    IMAGE_POLICY,
    gearDoctrine(),
    TOOL_POLICY,
    TONE,
  ].filter((section): section is string => Boolean(section));

  return sections.join('\n\n');
}

