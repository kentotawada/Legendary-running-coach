/**
 * 説明図。
 *
 * ストレッチのやり方も走り方も、言葉だけでは形が伝わらない。
 * かといって、その場で画像を作らせるのは選ばなかった。
 * 人体の姿勢は指の数や関節の向きが少し狂うだけで「間違ったお手本」になり、
 * それを見て真似た人が故障する。図は全て手で描き、目で確かめたものだけを置く。
 *
 * モデルは id を選ぶだけで、絵そのものには触れない。
 * 道具のリンクと同じ考え方で、URL や画像をモデルに書かせない。
 */

export type FigureCategory = 'stretch' | 'form' | 'strength';

export const FIGURE_CATEGORY_LABEL: Record<FigureCategory, string> = {
  stretch: 'ストレッチ',
  form: '走り方',
  strength: '補強',
};

export interface Figure {
  id: string;
  title: string;
  category: FigureCategory;
  /** どんな時に出すか。プロンプトに載せ、モデルが選べるようにする。 */
  when: string;
  /** 何のためにやるのか。カードの先頭に出す。 */
  purpose: string;
  /** 手順。図と突き合わせて読めるよう、順番と体の部位を明示する。 */
  steps: string[];
  /** やってはいけないこと。図だけでは伝わらない危険を書く。 */
  cautions: string[];
  /** 目安の時間や回数。 */
  dose?: string;
}

