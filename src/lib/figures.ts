export function findFigure(id: string | undefined): Figure | undefined {
  if (!id) return undefined;
  return FIGURES.find((figure) => figure.id === id);
}

/**
 * プロンプトに差し込む図の一覧。
 * 存在しない id を書かれると画面に何も出ないので、選べるものを全部並べる。
 */
export function figureDoctrine(): string {
  const lines = [
    '# 図を使って説明する',
    '',
    'ストレッチのやり方、走り方、補強の動きは、**言葉だけでは形が伝わりません。**',
    '説明する時は、用意された図を一緒に出してください。',
    '',
    '```figure',
    '{"id":"stretch-hamstring"}',
    '```',
    '',
    '- **id は下の一覧にあるものだけ。** 無いものを書くと、画面には何も出ません。',
    '- 画像のURLや、自分で考えた図の説明を本文に書いてはなりません。',
    '- 図の前後には必ず一言ずつ地の文を添える。図だけを投げつけない。',
    '- 1つの返答に図は**2つまで**。多いと本文が埋もれます。',
    '- 手順と注意は図のカードに載ります。本文で同じ手順を繰り返さないこと。',
    '',
    '使える図:',
  ];

  for (const category of ['stretch', 'form', 'strength'] as FigureCategory[]) {
    lines.push(`- ${FIGURE_CATEGORY_LABEL[category]}`);
    for (const figure of FIGURES.filter((f) => f.category === category)) {
      lines.push(`  - \`${figure.id}\` ${figure.title} — ${figure.when}`);
    }
  }

  return lines.join('\n');
}
